added_count = 0
updated_count = 0

for src, tr in translations.items():
    existing = frappe.db.sql("SELECT name, translated_text FROM `tabTranslation` WHERE BINARY source_text = %s AND language = 'vi'", (src,))
    if existing:
        doc_name, current_tr = existing[0]
        if current_tr != tr:
            doc = frappe.get_doc("Translation", doc_name)
            doc.translated_text = tr
            doc.save(ignore_permissions=True)
            updated_count += 1
    else:
        doc = frappe.new_doc("Translation")
        doc.language = "vi"
        doc.source_text = src
        doc.translated_text = tr
        doc.insert(ignore_permissions=True)
        added_count += 1

frappe.db.commit()
frappe.clear_cache()
print(f"Đã bổ sung thành công {added_count} bản dịch mới và cập nhật {updated_count} bản dịch!")
